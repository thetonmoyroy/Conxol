import assert from "node:assert/strict";
import { diagnosticTabsReducer, LiveDiagnosticRun, MAX_DIAGNOSTIC_TABS } from "../src/live-diagnostic-run.ts";

const mtr = new LiveDiagnosticRun();
const ping = new LiveDiagnosticRun();
assert.equal(mtr.begin("mtr-1"), true);
assert.equal(ping.begin("ping-1"), true);
assert.equal(mtr.begin("duplicate"), false);
assert.equal(mtr.accepts("ping-1"), false);
assert.equal(ping.accepts("mtr-1"), false);
assert.equal(mtr.accepts("mtr-1"), true, "events can arrive before start IPC resolves");
assert.equal(mtr.requestStop(), "mtr-1");
assert.equal(mtr.shouldCancel("mtr-1"), true, "early Stop must be retried once the worker exists");
assert.equal(ping.shouldCancel("ping-1"), false, "Stop is isolated to its instance");
mtr.acknowledgeCancel("mtr-1");
assert.equal(mtr.shouldCancel("mtr-1"), false);
mtr.finish("mtr-1");
assert.equal(mtr.accepts("mtr-1"), false, "ignore progress after completion");
assert.equal(ping.accepts("ping-1"), true);
assert.equal(mtr.begin("mtr-2"), true);
assert.equal(mtr.accepts("mtr-1"), false, "late events must not affect a newer run");
mtr.finish("mtr-1");
assert.equal(mtr.accepts("mtr-2"), true);
assert.equal(mtr.dispose(), "mtr-2");
assert.equal(mtr.accepts("mtr-2"), false);
assert.equal(mtr.shouldCancel("mtr-2"), true, "closing before the start response must still cancel its eventual worker");
assert.equal(mtr.begin("mtr-3"), false);
ping.finish("ping-1");
assert.equal(ping.requestStop(), null);
assert.equal(ping.shouldCancel("ping-1"), false);

let tabs = { tabs: [], active: { mtr: null, ping: null } };
tabs = diagnosticTabsReducer(tabs, { type: "add", id: "mtr-a", kind: "mtr" });
tabs = diagnosticTabsReducer(tabs, { type: "add", id: "ping-a", kind: "ping" });
tabs = diagnosticTabsReducer(tabs, { type: "add", id: "mtr-b", kind: "mtr" });
tabs = diagnosticTabsReducer(tabs, { type: "update", id: "mtr-a", target: "192.0.2.1", state: "running" });
assert.equal(tabs.tabs.find(tab => tab.id === "ping-a").state, "idle");
tabs = diagnosticTabsReducer(tabs, { type: "close", id: "mtr-b" });
assert.equal(tabs.active.mtr, "mtr-a");
assert.equal(tabs.active.ping, "ping-a");
assert.equal(tabs.tabs.find(tab => tab.id === "mtr-a").target, "192.0.2.1");
for (let i = 0; i < 10; i++) tabs = diagnosticTabsReducer(tabs, { type: "add", id: `extra-${i}`, kind: "ping" });
assert.equal(tabs.tabs.length, MAX_DIAGNOSTIC_TABS);
assert.equal(diagnosticTabsReducer(tabs, { type: "add", id: "overflow", kind: "mtr" }), tabs);
